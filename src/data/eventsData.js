/**
 * Helper to retrieve an event by ID or sub-activity ID.
 * If a sub-activity ID is supplied, it gracefully returns the parent event.
 */
export const getEventById = (id) => {
  if (!id) return null;
  const direct = eventsData.find((e) => e.id === id);
  if (direct) return direct;
  const parent = eventsData.find((e) => e.timeline?.some((t) => t.id === id));
  if (parent) return parent;
  return null;
};
